import { expect, test, type Locator, type Page } from "@playwright/test"
import { shouldSkipBrowserSpecs } from "./_helpers"

async function arrowTo(page: Page, destination: Locator) {
  for (let attempt = 0; attempt < 60; attempt += 1) {
    if (await destination.evaluate(element => element === document.activeElement)) break
    await page.keyboard.press("ArrowDown")
  }
  await expect(destination).toBeFocused()
}

test.describe("More disclosure keyboard candidates", () => {
  test.skip(shouldSkipBrowserSpecs(), "Set E2E_BASE_URL to run browser specs")
  test.use({ serviceWorkers: "block" })

  test("a crowded hierarchy skips collapsed links and keeps continuous More keyboard navigation visible", async ({ page, request, baseURL }) => {
    const headers = { origin: new URL(baseURL!).origin }
    const previous = (await (await request.get("/api/settings")).json()).sidebar_config
    const areaResponse = await request.post("/api/areas", { headers, data: { name: "Keyboard Area" } })
    expect(areaResponse.status()).toBe(201)
    const { id: areaId } = await areaResponse.json()
    const projectIds: string[] = []
    try {
      // Bound the request count and concurrency while exceeding both old inner scroll caps.
      for (let batch = 0; batch < 4; batch += 1) {
        const created = await Promise.all(Array.from({ length: 6 }, async (_, index) => {
          const title = `Keyboard Project ${String(batch * 6 + index).padStart(2, "0")}`
          const response = await request.post("/api/projects", { headers, data: { title, area_id: areaId } })
          expect(response.status()).toBe(201)
          const { id } = await response.json()
          projectIds.push(id)
          return { id, title }
        }))
        expect(created).toHaveLength(6)
      }
      expect((await request.put("/api/settings", { headers, data: { key: "sidebar_config", value: {
        order: ["dashboard", "today", "boards", "planning"],
      } } })).ok()).toBe(true)
      await page.addInitScript(() => {
        localStorage.setItem("meitheal-appearance", JSON.stringify({ navigation: "navbar" }))
        localStorage.setItem("meitheal_project_nav_group_collapsed", "true")
        sessionStorage.setItem("meitheal-boards-collapsed", "true")
      })
      await page.setViewportSize({ width: 1100, height: 900 })
      await page.goto("/today")
      const row = page.locator('[data-nav-overflow="sidebar"]')
      await expect(row).toHaveAttribute("data-nav-overflow-active", "")
      await row.evaluate(element => { element.style.maxWidth = "180px" })
      const more = row.locator("[data-nav-overflow-more]")
      const summary = more.locator(":scope > summary")
      const menu = more.locator("[data-nav-overflow-menu]")
      const boards = row.locator('[data-sidebar-group="boards"]')
      const boardsLink = boards.locator(':scope > .nav-row a[data-page="boards"]')
      const boardsToggle = boards.locator("[data-sidebar-boards-toggle]")
      const household = boards.locator('[data-sidebar-household] > a')
      const areas = boards.locator("#sidebar-areas-group")
      const areasSummary = areas.locator(":scope > summary")
      const areaProjects = boards.locator(`[data-area-projects="${areaId}"] a.stree__project-link`)
      await expect(areaProjects).toHaveCount(24)
      const project = areaProjects.last()
      const firstProject = boards.locator("a.stree__project-link").first()
      const planning = row.locator('a[data-page="planning"]')
      await expect(menu.locator('[data-sidebar-group="boards"]')).toHaveCount(1)
      await expect(boardsToggle).toHaveAttribute("aria-expanded", "false")
      await expect(household).toBeHidden()
      await summary.press("ArrowDown")
      await arrowTo(page, boardsLink)
      await page.keyboard.press("ArrowDown")
      await expect(planning).toBeFocused()
      await page.keyboard.press("ArrowUp")
      await expect(boardsLink).toBeFocused()

      // Native Tab reaches the disclosure; no hidden descendant is forced into focus.
      await page.keyboard.press("Tab")
      await expect(boardsToggle).toBeFocused()
      await page.keyboard.press("Enter")
      await expect(boardsToggle).toHaveAttribute("aria-expanded", "true")
      await expect(household).toBeVisible()
      await page.keyboard.press("Shift+Tab")
      await expect(boardsLink).toBeFocused()
      await page.keyboard.press("ArrowDown")
      await expect(household).toBeFocused()
      await expect(areas).not.toHaveAttribute("open", "")
      await expect(project).toBeHidden()
      await page.keyboard.press("ArrowDown")
      await expect(planning).toBeFocused()
      await page.keyboard.press("ArrowUp")
      await expect(household).toBeFocused()

      // The original Household destination retains focus in the wide Boards dropdown.
      await row.evaluate(element => { element.style.maxWidth = "none" })
      await page.setViewportSize({ width: 2200, height: 900 })
      await expect(more).toBeHidden()
      await expect(household).toBeFocused()
      await expect(household).toBeInViewport({ ratio: 1 })
      await expect(boardsLink).toBeInViewport({ ratio: 1 })
      await page.keyboard.press("Escape")
      await expect(boardsToggle).toHaveAttribute("aria-expanded", "false")
      await expect(boardsToggle).toBeFocused()
      await expect(household).toBeHidden()
      await page.keyboard.press("Enter")
      await expect(boardsToggle).toHaveAttribute("aria-expanded", "true")
      await page.keyboard.press("Tab")
      await expect(household).toBeFocused()
      await page.locator("#main-content").click({ position: { x: 20, y: 20 } })
      await expect(boardsToggle).toHaveAttribute("aria-expanded", "false")
      await expect(household).toBeHidden()
      await boardsToggle.press("Enter")
      await expect(boardsToggle).toHaveAttribute("aria-expanded", "true")
      await page.keyboard.press("Tab")
      await expect(household).toBeFocused()
      await page.keyboard.press("ArrowRight")
      await expect(planning).toBeFocused()
      await page.keyboard.press("ArrowLeft")
      await expect(household).toBeFocused()
      await row.evaluate(element => { element.style.maxWidth = "180px" })
      await page.setViewportSize({ width: 1100, height: 900 })
      await expect(menu.locator('[data-sidebar-group="boards"]')).toHaveCount(1)
      await expect(household).toBeFocused()

      await page.keyboard.press("Tab")
      await expect(areasSummary).toBeFocused()
      await page.keyboard.press("Enter")
      await expect(areas).toHaveAttribute("open", "")
      await expect(project).toBeVisible()
      expect(await menu.evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true)
      await page.keyboard.press("Shift+Tab")
      await expect(household).toBeFocused()
      await page.keyboard.press("Tab")
      await expect(areasSummary).toBeFocused()
      await page.keyboard.press("Tab")
      await expect(boards.locator(".stree__area-toggle").first()).toBeFocused()
      await page.keyboard.press("ArrowDown")
      await expect(firstProject).toBeFocused()
      await page.keyboard.press("ArrowUp")
      await expect(household).toBeFocused()
      await page.keyboard.press("ArrowDown")
      await expect(firstProject).toBeFocused()
      await arrowTo(page, project)
      await expect(project).toBeFocused()
      await expect(project).toHaveAttribute("tabindex", "0")
      await page.keyboard.press("ArrowDown")
      await expect(planning).toBeFocused()
      await page.keyboard.press("ArrowUp")
      await expect(project).toBeFocused()
      await expect(project).toBeInViewport({ ratio: 1 })
      const focusedBox = await project.boundingBox()
      const menuBox = await menu.boundingBox()
      expect(focusedBox!.y).toBeGreaterThanOrEqual(menuBox!.y)
      expect(focusedBox!.y + focusedBox!.height).toBeLessThanOrEqual(menuBox!.y + menuBox!.height + 1)
      await page.keyboard.press("End")
      await expect(menu.locator("a").last()).toBeFocused()
      await page.keyboard.press("Home")
      await expect(menu.locator("a").first()).toBeFocused()

      await page.keyboard.press("Escape")
      await expect(more).not.toHaveAttribute("open", "")
      await expect(summary).toBeFocused()
      await summary.press("ArrowDown")
      await arrowTo(page, boardsLink)
      await page.keyboard.press("ArrowDown")
      await expect(household).toBeFocused()
      await page.keyboard.press("ArrowDown")
      await expect(firstProject).toBeFocused()
      await arrowTo(page, project)
      await expect(project).toBeFocused()
      await row.evaluate(element => { element.style.maxWidth = "none" })
      await page.setViewportSize({ width: 2200, height: 900 })
      await expect(more).toBeHidden()
      await expect(project).toBeFocused()
      await expect(project).toBeInViewport({ ratio: 1 })
      await expect(areas).toHaveAttribute("open", "")
      await expect(project).not.toHaveAttribute("tabindex", "-1")
      await page.setViewportSize({ width: 320, height: 900 })
      await expect(row).not.toHaveAttribute("data-nav-overflow-active", "")
      await expect(areas).toHaveAttribute("open", "")
      await expect(page.locator("#sidebar")).toHaveClass(/open/)
      await expect(project).toBeFocused()
      await expect(project).toBeInViewport({ ratio: 1 })
      await page.keyboard.press("Escape")
      await expect(page.locator("#sidebar")).not.toHaveClass(/open/)
      await expect(page.locator("#menu-toggle")).toBeFocused()
      await page.locator("#menu-toggle").click()
      await expect(page.locator("#sidebar")).toHaveClass(/open/)
      await expect(household).toBeVisible()
      const today = row.locator('a[data-page="today"]')
      await expect(today).toBeFocused()
      await expect(today).toBeInViewport({ ratio: 1 })
      await page.keyboard.press("Tab")
      await expect(boardsLink).toBeFocused()
      await page.keyboard.press("Tab")
      await expect(boardsToggle).toBeFocused()
      await page.keyboard.press("Tab")
      await expect(household).toBeFocused()
      await page.keyboard.press("Tab")
      await expect(areasSummary).toBeFocused()
      await page.keyboard.press("Tab")
      await expect(boards.locator(".stree__area-toggle").first()).toBeFocused()
      await page.keyboard.press("ArrowDown")
      await expect(firstProject).toBeFocused()
      await arrowTo(page, project)
      await expect(project).toBeFocused()
      await expect(project).toBeInViewport({ ratio: 1 })
    } finally {
      expect((await request.put("/api/settings", { headers, data: { key: "sidebar_config", value: previous ?? null } })).ok()).toBe(true)
      for (let offset = 0; offset < projectIds.length; offset += 6) {
        const deleted = await Promise.all(projectIds.slice(offset, offset + 6).map(id => request.delete(`/api/projects/${id}`, { headers, data: {} })))
        for (const response of deleted) expect(response.ok()).toBe(true)
      }
      expect((await request.delete(`/api/areas/${areaId}`, { headers, data: {} })).ok()).toBe(true)
    }
  })
})
