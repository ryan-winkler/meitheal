import { expect, test } from "@playwright/test"
import { shouldSkipBrowserSpecs } from "./_helpers"

test.skip(shouldSkipBrowserSpecs(), "Set E2E_BASE_URL to run browser specs")
test.use({ serviceWorkers: "block" })

test("recreated sidebar restores pinned links and binds Tasks controls once", async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 960 })
  await page.goto("/tasks")

  const taskMenu = page.locator("#tasks-submenu-toggle")
  const creationMenu = page.locator("#sidebar-task-types [data-task-creation-toggle]")
  const pinnedView = page.locator('[data-task-view-pinned-item="calendar"]')
  const pinnedType = page.locator('#sidebar-task-types [data-task-nav-pinned-item="calendar_event"]')
  await taskMenu.click()
  await page.locator('#tasks-nav-submenu [data-task-view-pin="calendar"]').click()
  await expect(pinnedView).toBeVisible()
  await taskMenu.click()
  await creationMenu.click()
  await page.locator('#sidebar-task-types [data-task-creation-options] [data-task-nav-pin="calendar_event"]').click()
  await expect(pinnedType).toBeVisible()
  await creationMenu.click()

  await page.evaluate(() => Reflect.set(window, "sidebarReplacementProbe", true))
  await page.locator('#sidebar a[data-page="dashboard"]').click()
  await page.locator('[data-setup-invite] a[href="/setup"]').click()
  await expect(page).toHaveURL(/\/setup$/)
  await expect(page.locator("#sidebar")).toHaveCount(0)
  await page.goBack()

  await expect(pinnedView).toBeVisible()
  await expect(pinnedType).toBeVisible()
  expect(await page.evaluate(() => Reflect.get(window, "sidebarReplacementProbe"))).toBe(true)
  await taskMenu.click()
  await expect(taskMenu).toHaveAttribute("aria-expanded", "true")
  await expect(page.locator("#tasks-nav-submenu")).toBeVisible()
  await page.keyboard.press("Escape")
  await creationMenu.click()
  await expect(creationMenu).toHaveAttribute("aria-expanded", "true")
  await expect(page.locator("#sidebar-task-types [data-task-creation-options]")).toBeVisible()
  await page.keyboard.press("Escape")

  const edge = page.locator("#sidebar-edge-toggle")
  for (const collapsed of [true, false]) {
    await edge.click()
    const label = `${collapsed ? "Expand" : "Collapse"} sidebar (Ctrl+B)`
    await expect(edge).toHaveAttribute("aria-expanded", String(!collapsed))
    await expect(edge).toHaveAttribute("aria-label", label)
    await expect(edge).toHaveAttribute("title", label)
  }
})

test("sidebar can close again in desktop hover mode and on a phone", async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 960 })
  await page.addInitScript(() => {
    localStorage.setItem("meitheal-theme", "knight-rider")
    localStorage.setItem("meitheal-appearance", JSON.stringify({ sidebar: "hover" }))
    localStorage.setItem("meitheal-task-nav-prefs", JSON.stringify({ pinnedViews: ["table"] }))
  })
  await page.goto("/tasks")

  const edge = page.locator("#sidebar-edge-toggle")
  const sidebar = page.locator("#sidebar")
  const body = page.locator("body")
  const arrow = edge.locator(".sidebar-edge-toggle__icon")
  await expect(edge).toHaveAttribute("aria-expanded", "false")
  await edge.hover()
  await expect(edge).toHaveAttribute("aria-expanded", "false")
  await edge.click()
  await expect(edge).toHaveAttribute("aria-expanded", "true")
  await expect(body).not.toHaveClass(/sidebar-collapsed/)
  await expect(arrow).toHaveCSS("transform", "matrix(0, 1, -1, 0, 0, 0)")
  await edge.click()
  await expect(edge).toHaveAttribute("aria-expanded", "false")
  await expect(body).toHaveClass(/sidebar-collapsed/)
  await expect(arrow).toHaveCSS("transform", "matrix(0, -1, 1, 0, 0, 0)")
  await edge.press("Enter")
  await expect(body).not.toHaveClass(/sidebar-collapsed/)
  await page.keyboard.press("Control+b")
  await expect(body).toHaveClass(/sidebar-collapsed/)
  await edge.hover()
  await expect(body).toHaveClass(/sidebar-collapsed/)
  const dashboardLink = sidebar.locator('a[data-page="dashboard"]')
  await dashboardLink.hover()
  await expect(body).not.toHaveClass(/sidebar-collapsed/)
  const unpin = sidebar.locator('[data-task-view-pinned-item="table"]').getByRole("button", { name: "Unpin Table from navigation" })
  await unpin.focus()
  await page.evaluate(() => window.dispatchEvent(new CustomEvent("meitheal:theme-changed")))
  await expect(unpin).toBeFocused()
  await expect(body).not.toHaveClass(/sidebar-collapsed/)
  await edge.click()
  await expect(body).toHaveClass(/sidebar-collapsed/)

  const menu = page.locator("#menu-toggle")
  const close = sidebar.getByRole("button", { name: "Close sidebar" })
  await expect(menu).toHaveAttribute("data-drawer-ready", "true")
  // The desktop edge toggle disappears on a phone. Focus a link present at both widths.
  await dashboardLink.focus()
  await expect(dashboardLink).toBeFocused()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(menu).toHaveAttribute("aria-expanded", "true")
  await expect(dashboardLink).toBeFocused()
  await close.click()
  await expect(menu).toHaveAttribute("aria-expanded", "false")
  await expect(menu).toBeFocused()
  await expect(sidebar).not.toHaveClass(/open/)
  await menu.press("Enter")
  await close.focus()
  for (const key of ["Shift+Tab", ...Array<string>(24).fill("Tab")]) {
    await page.keyboard.press(key)
    expect(await sidebar.evaluate(drawer => drawer.contains(document.activeElement))).toBe(true)
  }
  await page.keyboard.press("Control+k")
  await expect(page.locator("#search-hub-input")).toBeFocused()
  await page.keyboard.press("Tab")
  expect(await page.locator("#search-hub-overlay").evaluate(overlay => overlay.contains(document.activeElement))).toBe(true)
  await page.keyboard.press("Escape")
  await expect(page.locator("#search-hub-overlay")).toBeHidden()
  await expect(menu).toHaveAttribute("aria-expanded", "true")
  await close.press("Enter")
  await expect(menu).toHaveAttribute("aria-expanded", "false")
  await expect(menu).toBeFocused()

  await menu.click()
  await expect(menu).toHaveAttribute("aria-expanded", "true")
  await close.focus()
  await page.mouse.click(384, 400)
  await expect(menu).toHaveAttribute("aria-expanded", "false")
  await expect(menu).toBeFocused()
})
